"""Render production Settings panels offscreen with isolated sample data."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


LIB = Path(__file__).resolve().parents[1]
PROJECT = LIB.parents[1]
SECTIONS = ("general", "alerts", "providers", "guide", "about")
REFRESH_PREVIEWS = (
    {"name": "general-refresh-default-5min", "minutes": 5},
    {"name": "general-refresh-15min", "minutes": 15},
    {"name": "general-refresh-max-60min", "minutes": 60},
)
PROVIDERS = ["codex", "claude", "cursor", "opencode", "copilot", "kiro",
             "openrouter", "anthropic-api", "openai-api", "google-cloud",
             "grok-bot", "commandcode", "deepinfra", "deepseek", "kimi", "minimax"]
NAMES = {"codex": "Codex", "claude": "Claude", "cursor": "Cursor",
         "opencode": "OpenCode", "copilot": "Copilot", "kiro": "Kiro",
         "openrouter": "OpenRouter", "anthropic-api": "Anthropic API",
         "openai-api": "OpenAI API", "google-cloud": "Google Cloud",
         "grok-bot": "Grok Bot", "commandcode": "Command Code",
         "deepinfra": "DeepInfra", "deepseek": "DeepSeek", "kimi": "Kimi", "minimax": "MiniMax"}


def clear_previous_captures(output, frontend):
    # Drop only files generated by this helper, including the retired tab.
    for name in (*SECTIONS, "alerts-advanced", "appearance",
                 *(entry["name"] for entry in REFRESH_PREVIEWS)):
        for suffix in ("", "-middle", "-bottom"):
            (output / f"{frontend}-{name}{suffix}.png").unlink(missing_ok=True)


def render_quickshell(output, renderer="software", refresh_only=False):
    runner = os.environ.get("QMLTESTRUNNER") or shutil.which("qmltestrunner")
    if not runner:
        candidate = Path("/usr/lib/qt6/bin/qmltestrunner")
        if candidate.exists():
            runner = str(candidate)
    if not runner:
        raise RuntimeError("Install Qt Quick Test or set QMLTESTRUNNER to its executable.")
    version = json.loads((PROJECT / "package.json").read_text(encoding="utf-8"))["version"]
    with tempfile.TemporaryDirectory(prefix="ai-status-settings-preview-") as directory:
        root = Path(directory)
        for name in ("qs", "Quickshell"):
            shutil.copytree(LIB / "tests/qml" / name, root / name)
        shutil.copytree(LIB / "quickshell", root / "plugin")
        shutil.copy2(LIB / "tests/qml/Model.qml", root / "plugin/Model.qml")
        shutil.copytree(LIB / "assets", root / "assets")
        preview = '''
import QtQuick
import QtTest
import "plugin" as Plugin
Item {
    width: 380
    height: 680
    Plugin.Panel { id: panel; width: 380; height: 680 }
    TestCase {
        name: "SettingsPreviews"
        when: windowShown
        function captureViews(name, captures) {
            const scroller = findChild(panel, "panel-scroller")
            scroller.contentY = 0
            wait(150)
            const top = "quickshell-" + name + ".png"
            verify(grabImage(findChild(panel, "panel-surface")).save(OUTPUT + "/" + top))
            captures.push(top)
            const range = Math.max(0, scroller.contentHeight - scroller.height)
            console.info("SCROLL_RANGE " + name + " " + range)
            const visibleHeight = scroller.height - scroller.navigationInset
            if (range > visibleHeight) {
                scroller.contentY = range / 2
                wait(150)
                const middle = "quickshell-" + name + "-middle.png"
                verify(grabImage(findChild(panel, "panel-surface")).save(OUTPUT + "/" + middle))
                captures.push(middle)
            }
            if (range > 0) {
                scroller.contentY = range
                wait(150)
                const bottom = "quickshell-" + name + "-bottom.png"
                verify(grabImage(findChild(panel, "panel-surface")).save(OUTPUT + "/" + bottom))
                captures.push(bottom)
            }
            scroller.contentY = 0
            wait(50)
        }
        function test_render() {
            Plugin.Model.reset()
            const snapshot = JSON.parse(JSON.stringify(Plugin.Model.snapshot))
            snapshot.version = {current: VERSION, has_update: false}
            snapshot.about.version = VERSION
            snapshot.settings.order = PROVIDERS
            snapshot.settings.names = NAMES
            snapshot.settings.enabled = PROVIDERS.slice(0, 4)
            snapshot.settings.display = {show_provider: true, show_model: true, show_metric: false, show_pct: true}
            snapshot.settings.iconMode = "logo"
            snapshot.settings.refreshIntervalMinutes = 5
            snapshot.selected = {provider: "codex", idx: 0, metric: "weekly"}
            Plugin.Model.snapshot = snapshot
            panel.configure()
            const settings = findChild(panel, "panel-settings-page")
            const captures = []
            verify(settings !== null)
            verify(settings.sections.every(section => section.key !== "appearance"))
            settings.selectSection("general")
            const slider = findChild(settings, "refresh-interval-slider")
            verify(slider !== null && slider.visible)
            compare(slider.from, 5)
            compare(slider.to, 60)
            compare(slider.stepSize, 5)
            compare(settings.refreshIntervalMinutes, 5)
            for (const entry of REFRESH_PREVIEWS) {
                settings.refreshIntervalMinutes = entry.minutes
                wait(150)
                compare(slider.value, entry.minutes)
                verify(findChild(settings, "settings-usage-display").visible)
                verify(findChild(panel, "settings-footer").visible)
                compare(Plugin.Model.snapshot.settings.refreshIntervalMinutes, 5)
                compare(Plugin.Model.saved, null)
                compare(Plugin.Model.actions.length, 0)
                captureViews(entry.name, captures)
            }
            settings.refreshIntervalMinutes = 5
            for (const section of SECTIONS) {
                settings.selectSection(section)
                wait(150)
                compare(settings.section, section)
                captureViews(section, captures)
                if (section === "alerts") {
                    settings.alertsAdvanced = true
                    captureViews("alerts-advanced", captures)
                    settings.alertsAdvanced = false
                }
            }
            console.info("CAPTURE_FILES " + JSON.stringify(captures))
        }
    }
}
'''
        sections = () if refresh_only else SECTIONS
        for token, value in {"VERSION": version, "PROVIDERS": PROVIDERS, "NAMES": NAMES,
                             "SECTIONS": sections, "REFRESH_PREVIEWS": REFRESH_PREVIEWS,
                             "OUTPUT": str(output)}.items():
            preview = preview.replace(token, json.dumps(value))
        (root / "tst_Preview.qml").write_text(preview, encoding="utf-8")
        env = dict(os.environ, QML_XHR_ALLOW_FILE_READ="1")
        if renderer == "opengl":
            env.update(QT_QPA_PLATFORM="xcb", QSG_RHI_BACKEND="opengl", LIBGL_ALWAYS_SOFTWARE="1")
            env.pop("QT_QUICK_BACKEND", None)
        else:
            env.update(QT_QPA_PLATFORM="offscreen", QT_QUICK_BACKEND="software")
        clear_previous_captures(output, "quickshell")
        result = subprocess.run([runner, "-input", str(root), "-import", str(root)], env=env,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        print(result.stdout, end="")
        result.check_returncode()
        marker = "CAPTURE_FILES "
        capture_line = next(line for line in result.stdout.splitlines() if marker in line)
        captures = json.loads(capture_line.split(marker, 1)[1])
        expected = {f"quickshell-{entry['name']}.png" for entry in REFRESH_PREVIEWS}
        if not refresh_only:
            expected.update(f"quickshell-{section}.png" for section in (*SECTIONS, "alerts-advanced"))
        if not expected.issubset(captures):
            raise RuntimeError("Qt did not capture every Settings section.")
        for name in captures:
            if not (output / name).is_file():
                raise RuntimeError(f"Qt did not save {name}.")


def render_windows(output, refresh_only=False):
    # The same fixture used by native desktop tests isolates all config/state
    # files, stops collectors/timers and suppresses the system tray.
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    sys.path.insert(0, str(LIB / "src"))
    sys.path.insert(0, str(LIB / "tests"))
    from unittest.mock import patch
    from PySide6.QtTest import QTest
    from core import config, paths, state, tray
    from test_tray import DesktopTests

    DesktopTests.setUpClass()
    case = DesktopTests()
    case.setUp()
    try:
        case.app.setStyle("Fusion")
        case.app.setFont(tray.panel_font())
        config.save_config(PROVIDERS[:4])
        state.save_selected({"provider": "codex", "idx": 0, "metric": "weekly",
                             "show_provider": True, "show_model": True,
                             "show_metric": False, "show_pct": True, "icon_mode": "logo",
                             "refresh_interval_minutes": 5})
        panel = case.dashboard
        panel.selected = state.load_selected()
        panel.data = {
            "codex": [{"provider": "Codex (Plus)", "_idx": 0, "metrics": [
                {"type": "rolling", "percentage": 3, "reset_in_seconds": 15900},
                {"type": "weekly", "percentage": 25, "reset_in_seconds": 561600}]}],
            "claude": [{"provider": "Claude (Max)", "_idx": 0, "metrics": [
                {"type": "rolling", "percentage": 2, "reset_in_seconds": 17700},
                {"type": "weekly", "percentage": 24, "reset_in_seconds": 316800}]}],
        }
        panel.draw()
        with patch.object(paths, "IS_WINDOWS", True), \
             patch.object(tray, "startup_enabled", return_value=False), \
             patch.object(panel, "isActiveWindow", return_value=True), \
             patch.object(panel, "refresh") as refresh, \
             patch.object(panel, "apply_reset") as apply_reset:
            panel.show()
            panel.configure()
            def capture_views(name):
                scroll = panel.settings_scroll.verticalScrollBar()
                scroll.setValue(0)
                QTest.qWait(150)
                assert panel.grab().save(str(output / f"windows-{name}.png"))
                maximum = scroll.maximum()
                print(f"Windows {name} scroll range: {maximum}")
                visible_height = panel.settings_scroll.viewport().height() - panel.settings_navigation.height()
                if maximum > visible_height:
                    scroll.setValue(maximum // 2)
                    QTest.qWait(150)
                    assert panel.grab().save(str(output / f"windows-{name}-middle.png"))
                if maximum > 0:
                    scroll.setValue(maximum)
                    QTest.qWait(150)
                    assert panel.grab().save(str(output / f"windows-{name}-bottom.png"))
                scroll.setValue(0)
                QTest.qWait(50)

            clear_previous_captures(output, "windows")
            assert "appearance" not in panel.settings_view.sections
            assert panel.settings_view.refresh_interval_minutes() == 5
            for entry in REFRESH_PREVIEWS:
                panel.settings_view.select_section("general")
                panel.settings_view.refresh_interval.setValue(state.REFRESH_INTERVAL_MINUTES.index(entry["minutes"]))
                QTest.qWait(150)
                assert panel.settings_view.refresh_interval_minutes() == entry["minutes"]
                assert panel.settings_view.refresh_interval_label.text() == f"{entry['minutes']} min"
                assert state.get_refresh_interval_minutes(state.load_selected()) == 5
                capture_views(entry["name"])
            panel.settings_view.refresh_interval.setValue(0)
            for section in (() if refresh_only else SECTIONS):
                panel.settings_view.select_section(section)
                QTest.qWait(150)
                capture_views(section)
                if section == "alerts":
                    panel.settings_view.notification_advanced_button.setChecked(True)
                    capture_views("alerts-advanced")
                    panel.settings_view.notification_advanced_button.setChecked(False)
            refresh.assert_not_called()
            apply_reset.assert_not_called()
            panel.hide()
    finally:
        case.doCleanups()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=("quickshell", "windows", "all"), default="quickshell")
    parser.add_argument("--qml-renderer", choices=("software", "opengl"), default="software",
                        help="OpenGL uses an X display and includes the production alpha fade.")
    parser.add_argument("--refresh-only", action="store_true",
                        help="Capture General at the default 5, selected 15 and maximum 60 minutes.")
    parser.add_argument("--output", type=Path, default=PROJECT / "docs/screenshots/settings-submenus")
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    if args.platform in ("quickshell", "all"):
        render_quickshell(output, args.qml_renderer, args.refresh_only)
    if args.platform in ("windows", "all"):
        render_windows(output, args.refresh_only)
    print(f"Rendered sample-data Settings previews in {output}")


if __name__ == "__main__":
    main()
